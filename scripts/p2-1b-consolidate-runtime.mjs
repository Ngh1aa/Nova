const jsHeader = `/* GENERATED BY scripts/p2-1b-consolidate-runtime.mjs\n   P2.1B physically bundles the verified historical foundation passes in their\n   original execution order so app.html has one canonical renderer dependency.\n   Do not hand-edit this generated file; edit an owning source/contract and rerun\n   the consolidator. Historical inputs remain in-repo for provenance only. */\nwindow.NovaCurrentRuntime = window.NovaCurrentRuntime || {};\nwindow.NovaCurrentRuntime.foundation = Object.freeze({\n  owner: 'assets/nova-current-renderer.js',\n  architecture: 'canonical-foundation-bundle',\n  bundled: true,\n  sourceCount: ${jsInputs.length}\n});\n`;

const cssHeader = `/* GENERATED BY scripts/p2-1b-consolidate-runtime.mjs\n   P2.1B preserves the verified stylesheet cascade while collapsing historical\n   foundation links into assets/nova-current.css. Motion remains a separate\n   cross-cutting runtime concern. */\n`;

const section = (file, content, kind) => `\n/* ===== P2.1B ${kind} SOURCE: ${file} ===== */\n${content.trimEnd()}\n/* ===== END P2.1B ${kind} SOURCE: ${file} ===== */\n`;

const bundledJs = jsHeader + jsInputs.map((file) => section(file, read(file), 'JS')).join('');
const bundledCss = cssHeader + cssInputs.map((file) => section(file, read(file), 'CSS')).join('');
write('assets/nova-current-renderer.js', bundledJs);
write('assets/nova-current.css', bundledCss);

