import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');
const write = (file, content) => {
  const target = path.join(root, file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, content.endsWith('\n') ? content : `${content}\n`, 'utf8');
};

const archiveDir = 'assets/legacy/p2-1a-canonical';
const rendererArchive = `${archiveDir}/nova-current-renderer.p2-1a.js`;

if (!fs.existsSync(path.join(root, rendererArchive))) {
  write(rendererArchive, read('assets/nova-current-renderer.js'));
}

const jsInputs = [
  'assets/nova.js',
  'assets/nova-redesign.js',
  'assets/nova-financial-intelligence.js',
  'assets/accessibility.js',
  'assets/nova-ios26.js',
  'assets/nova-pastel-dashboard.js',
  'assets/nova-dashboard-v2.js',
  rendererArchive
];

// Pastel iOS redesign (2026-10-26): the historical 21-file cascade is replaced by
// one token-driven stylesheet. Old inputs stay in git history, not in the bundle.
const cssInputs = [
  'assets/nova-ui/tokens.css',
  'assets/nova-ui/shell.css',
  'assets/nova-ui/components.css',
  'assets/nova-ui/screens.css'
];

const normalizeCanonicalIdentity = (file, content) => {
  if (file !== 'assets/nova.js') return content;

  const brandMarkup = '<span class="brand-mark" aria-hidden="true">L</span><span>Ledger</span>';
  const novaBrandMarkup = '<img class="brand-lockup" src="assets/nova-logo.svg" alt="Nova">';
  const normalized = content
    .replaceAll(brandMarkup, novaBrandMarkup)
    .replace(/\bLedger\b/g, 'Nova')
    .replace(/LDG_/g, 'NVA_');

  if (/\bLedger\b/.test(normalized) || /LDG_/.test(normalized)) {
    throw new Error('P2.2 identity normalization failed: legacy predecessor identity remains in canonical foundation input.');
  }

  return normalized;
};

const jsHeader = `/* GENERATED BY scripts/p2-1b-consolidate-runtime.mjs\n   P2.1B physically bundles the verified historical foundation passes in their\n   original execution order so app.html has one canonical renderer dependency.\n   P2.2 normalizes historical predecessor identity at generation time so canonical\n   runtime source is Nova-native and does not depend on DOM identity rewrites.\n   Do not hand-edit this generated file; edit an owning source/contract and rerun\n   the consolidator. Historical inputs remain in-repo for provenance only. */\nwindow.NovaCurrentRuntime = window.NovaCurrentRuntime || {};\nwindow.NovaCurrentRuntime.foundation = Object.freeze({\n  owner: 'assets/nova-current-renderer.js',\n  architecture: 'canonical-foundation-bundle',\n  bundled: true,\n  sourceCount: ${jsInputs.length}\n});\n`;

const cssHeader = `/* GENERATED BY scripts/p2-1b-consolidate-runtime.mjs\n   Nova UI stylesheet bundle. Edit assets/nova-ui/*.css and rerun the script.\n   Motion remains a separate cross-cutting runtime concern. */\n`;

const section = (file, content, kind) => `\n/* ===== P2.1B ${kind} SOURCE: ${file} ===== */\n${content.trimEnd()}\n/* ===== END P2.1B ${kind} SOURCE: ${file} ===== */\n`;

const bundledJs = jsHeader + jsInputs.map((file) => section(file, normalizeCanonicalIdentity(file, read(file)), 'JS')).join('');
const bundledCss = cssHeader + cssInputs.map((file) => section(file, read(file), 'CSS')).join('');

if (/\bLedger\b/.test(bundledJs) || /LDG_/.test(bundledJs)) {
  throw new Error('P2.2 canonical renderer contains legacy predecessor identity.');
}

write('assets/nova-current-renderer.js', bundledJs);
write('assets/nova-current.css', bundledCss);

let app = read('app.html');
app = app.replace('<link rel="preload" href="assets/nova.js" as="script">', '<link rel="preload" href="assets/nova-current-renderer.js" as="script">');

// Historical stylesheet links that must never come back into app.html.
const absorbedStyles = [
  'nova.css',
  'accessibility.css',
  'ledger.css',
  'nova-redesign.css'
];
for (const file of absorbedStyles) {
  app = app.replace(new RegExp(`\\s*<link rel="stylesheet" href="assets/${file.replaceAll('.', '\\.')}">`, 'g'), '');
}

const absorbedScripts = [
  'nova.js',
  'nova-redesign.js',
  'nova-financial-intelligence.js',
  'accessibility.js',
  'nova-ios26.js',
  'nova-pastel-dashboard.js',
  'nova-dashboard-v2.js'
];
for (const file of absorbedScripts) {
  app = app.replace(new RegExp(`\\s*<script src="assets/${file.replaceAll('.', '\\.')}" defer><\\/script>`, 'g'), '');
}

write('app.html', app);

const manifest = {
  status: 'P2.1B_GENERATED',
  canonical_renderer: 'assets/nova-current-renderer.js',
  canonical_stylesheet: 'assets/nova-current.css',
  canonical_identity: {
    brand: 'Nova',
    transaction_prefix: 'NVA_',
    generation_owner: 'scripts/p2-1b-consolidate-runtime.mjs',
    runtime_identity_rewrite: false,
    historical_provenance_only: [
      'assets/nova.js',
      'assets/nova-brand-fixes.js'
    ]
  },
  separate_runtime_concerns: [
    'assets/nova-motion.js',
    'assets/nova-motion.css',
    'assets/nova-current-state.js',
    'assets/state-lab-launcher.js'
  ],
  bundled_js_sources: jsInputs,
  bundled_css_sources: cssInputs,
  runtime_absorbed_scripts: absorbedScripts.map((file) => `assets/${file}`),
  runtime_absorbed_styles: absorbedStyles.map((file) => `assets/${file}`),
  archive_snapshots: [rendererArchive],
  truth_boundary: 'Physical bundling preserves historical source order; canonical Nova identity is normalized at generation time. Behavior parity must still be proven by browser/QA gates before P2.2 is DONE_VERIFIED.'
};
write('docs/uiux/runtime-manifest.p2-1b.json', JSON.stringify(manifest, null, 2));

console.log(`P2.1B bundled ${jsInputs.length} JS sources and ${cssInputs.length} CSS sources with canonical Nova identity.`);
